import json

from vulntrace.eval.results_doc import MISSING_NOTE, cp1_cases_needing_notes, load_notes, render_cp1_doc
from vulntrace.paths import REPO_ROOT


def _mr(result, code=None, matched=()):
    return {"result": result, "error": {"code": code, "message": ""} if code else None,
            "details": {"matched_binary_symbols": list(matched)}}


REPORT = {
    "build_flags": ["-gcflags=all=-l"], "scoring_note": "note.",
    "environment": {"go_version": "go1.24.7", "goos": "linux", "goarch": "amd64"},
    "counts": {"cases": 3, "agreements": 1, "false_not_reachable": 1, "false_reachable": 0, "errors": 1},
    "cases": [
        {"id": "a", "category": "A", "truth": "REACHABLE", "predicted": "REACHABLE", "outcome": "AGREE",
         "method_results": [_mr("PRESENT", matched=["p.F"])]},
        {"id": "b", "category": "B", "truth": "REACHABLE", "predicted": "NOT_REACHABLE",
         "outcome": "FALSE_NOT_REACHABLE", "method_results": [_mr("ABSENT")]},
        {"id": "c", "category": "C", "truth": "REACHABLE", "predicted": "ERROR", "outcome": "ERROR",
         "method_results": [_mr("ERROR", code="UNSUPPORTED_SYMBOL_FORM")]},
    ],
    "inlining_comparison": [
        {"id": "a", "truth": "REACHABLE", "inlining_disabled": [{"result": "PRESENT"}],
         "inlining_enabled": [{"result": "ABSENT"}]},
    ],
}


def test_cases_needing_notes_are_mismatches_and_inlining_flips():
    assert cp1_cases_needing_notes(REPORT) == ["b", "c", "a"]


def test_render_uses_report_values_and_flags_missing_notes():
    doc = render_cp1_doc(REPORT, {"b": "explained."}, "results/x.json")
    assert "| b | B | REACHABLE | ABSENT | NOT_REACHABLE | FALSE_NOT_REACHABLE | - |" in doc
    assert "| c | C | REACHABLE | ERROR (UNSUPPORTED_SYMBOL_FORM) | ERROR | ERROR | - |" in doc
    assert "False NOT_REACHABLE: 1." in doc
    assert "- `b`: explained." in doc
    assert f"- `c`: {MISSING_NOTE}" in doc and f"- `a`: {MISSING_NOTE}" in doc
    assert "environment unknown" in doc


def test_committed_cp1_doc_is_generated_and_fully_explained():
    doc = (REPO_ROOT / "docs" / "results" / "CP1_LINKER_RESULTS.md").read_text(encoding="utf-8")
    assert "Generated by `python -m vulntrace results render --doc cp1`" in doc
    assert MISSING_NOTE not in doc


def test_notes_file_is_valid_json_of_strings():
    notes = load_notes("cp1_linker")
    assert notes and all(isinstance(k, str) and isinstance(v, str) and v for k, v in notes.items())
    json.dumps(notes)
