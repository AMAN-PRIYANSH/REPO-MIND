    assert "False NOT_REACHABLE: 1." in doc
    assert "- `b`: explained." in doc
    assert f"- `c`: {MISSING_NOTE}" in doc and f"- `a`: {MISSING_NOTE}" in doc
    assert "environment unknown" in doc


