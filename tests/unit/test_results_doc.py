def _mr(result, code=None, matched=()):
    return {"result": result, "error": {"code": code, "message": ""} if code else None,
            "details": {"matched_binary_symbols": list(matched)}}


REPORT = {
    "build_flags": ["-gcflags=all=-l"], "scoring_note": "note.",
    "environment": {"go_version": "go1.24.7", "goos": "linux", "goarch": "amd64"},
    "counts": {"cases": 3, "agreements": 1, "false_not_reachable": 1, "false_reachable": 0, "errors": 1},
    "cases": [
        {"id": "a", "category": "A", "truth": "REACHABLE", "predicted": "REACHABLE", "outcome": "AGREE",
         "method_results": [_mr("PRESENT", matched=["p.F"])]},
        {"id": "b", "category": "B", "truth": "REACHABLE", "predicted": "NOT_REACHABLE",
         "outcome": "FALSE_NOT_REACHABLE", "method_results": [_mr("ABSENT")]},
        {"id": "c", "category": "C", "truth": "REACHABLE", "predicted": "ERROR", "outcome": "ERROR",
         "method_results": [_mr("ERROR", code="UNSUPPORTED_SYMBOL_FORM")]},
    ],
    "inlining_comparison": [
        {"id": "a", "truth": "REACHABLE", "inlining_disabled": [{"result": "PRESENT"}],
         "inlining_enabled": [{"result": "ABSENT"}]},
    ],
}


def test_cases_needing_notes_are_mismatches_and_inlining_flips():
    assert cp1_cases_needing_notes(REPORT) == ["b", "c", "a"]


