"""CP8: the README, the final report and the interview notes.

- No number in them may be absent from `docs/results/summary.json` (the numeric rows and `parameters`), apart from a short, reasoned allowlist.
- Every "k of n" / "k/n" pair and every `[low, high]` interval in them must be one the summary holds.
- Every relative link must resolve (files, and `#anchors` into Markdown files).
- The wording limits the reviews set must hold.

Limits of this check, stated here so nobody over-trusts it: it catches numbers that are not in the summary and pairs/intervals that do not
exist there; it cannot tell that a correct number was attached to the wrong claim. The README key-results table is therefore generated by
code and compared exactly (test_cp8_summary.py); prose numbers are the part this test can only bound.
"""

import json
import re
from pathlib import Path

import pytest

from vulntrace.eval import summary as S
from vulntrace.paths import REPO_ROOT

DOCS = {"README.md": REPO_ROOT / "README.md", "docs/FINAL_REPORT.md": REPO_ROOT / "docs" / "FINAL_REPORT.md",
        "docs/INTERVIEW_NOTES.md": REPO_ROOT / "docs" / "INTERVIEW_NOTES.md"}
SUMMARY = json.loads((REPO_ROOT / "docs" / "results" / "summary.json").read_text(encoding="utf-8"))

# Numbers that are not results of this repository. Each needs a reason; a number is allowed in the named document only.
ALLOWED = {
    "docs/FINAL_REPORT.md": {
        "1.0": "schema version and similar, not a result",
    },
    "docs/INTERVIEW_NOTES.md": {},
    "README.md": {},
}
# Tokens allowed everywhere: years and tool versions that are checked against their source below.
GLOBAL_YEARS = {"2026"}


def _python_min() -> str:
    m = re.search(r'requires-python\s*=\s*">=([\d.]+)"', (REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    return m.group(1)


def numeric_leaves() -> list[float]:
    out: list[float] = []
    for sec in SUMMARY["sections"]:
        for r in sec["rows"]:
            for key in ("value", "ci_low", "ci_high", "n", "n_clusters", "k"):
                v = r.get(key)
                if isinstance(v, (int, float)) and not isinstance(v, bool):
                    out.append(abs(float(v)))  # the token regex drops a leading minus sign, so magnitudes are compared
    for v in SUMMARY["parameters"].values():
        out += [abs(float(x)) for x in (v if isinstance(v, list) else [v])]
    return out


def pairs() -> set[tuple[int, int]]:
    out = set()
    for sec in SUMMARY["sections"]:
        for r in sec["rows"]:
            if r["kind"] in ("rate", "count"):
                out.add((r["k"], r["n"]))
    return out


def intervals() -> list[tuple[float, float]]:
    return [(r["ci_low"], r["ci_high"]) for sec in SUMMARY["sections"] for r in sec["rows"] if r.get("ci_low") is not None]


FENCE = re.compile(r"```.*?```", re.S)
INLINE = re.compile(r"`[^`\n]*`")
LINK_TARGET = re.compile(r"\]\([^)]*\)")
AUTOLINK = re.compile(r"<https?://[^>]*>|https?://\S+")
COMMENT = re.compile(r"<!--.*?-->", re.S)
DATE = re.compile(r"\b\d{1,2} (?:Jan|Feb|Mar|Apr|May|Jun|Jul|Aug|Sep|Oct|Nov|Dec)[a-z]* \d{4}\b|\b\d{4}-\d{2}-\d{2}\b")
LISTNUM = re.compile(r"^\s*\d+[.)]\s", re.M)
HEADNUM = re.compile(r"^(#+)\s+\d+(?:\.\d+)*[.)]?\s", re.M)
SECTION_REF = re.compile(r"\b[Ss]ections?\s+\d+(?:\.\d+)?(?:(?:,|\s+and)\s+\d+(?:\.\d+)?)*")
NUMBER = re.compile(r"(?<![\w.@])\d+(?:\.\d+)*%?")


def prose(text: str) -> str:
    """The text whose numbers are checked: no code, link targets, comments or dates; the generated README block is checked elsewhere."""
    if S.README_BEGIN in text:
        head, rest = text.split(S.README_BEGIN, 1)
        text = head + rest.split(S.README_END, 1)[1]
    for pat in (COMMENT, FENCE, INLINE, LINK_TARGET, AUTOLINK, DATE):
        text = pat.sub(" ", text)
    text = HEADNUM.sub(r"\1 ", text)
    text = SECTION_REF.sub(" ", text)
    return LISTNUM.sub("", text)


def _matches(token: str, leaves: list[float]) -> bool:
    pct = token.endswith("%")
    t = token.rstrip("%")
    if t.count(".") >= 2:  # a version number
        return any(v == t or v.startswith(t + ".") for v in SUMMARY["go_versions"]) or t == _python_min()
    if "." in t and not pct:
        d = len(t.split(".")[1])
        x = float(t)
        tol = 0.5 * 10 ** -d + 1e-6
        return any(abs(v - x) <= tol for v in leaves) or any(v.startswith(t) for v in SUMMARY["go_versions"]) or t == _python_min()
    x = float(t)
    if pct:
        return any(abs(100 * v - x) <= 0.5 + 1e-6 for v in leaves) or x == SUMMARY["parameters"]["interval_percent"]
    return any(v == x for v in leaves)  # a whole number must be a whole number in the summary


def unexplained_numbers(doc: str, text: str) -> list[str]:
    leaves = numeric_leaves()
    allowed = set(ALLOWED.get(doc, {})) | GLOBAL_YEARS
    out = []
    for m in NUMBER.finditer(prose(text)):
        tok = m.group(0)
        if tok.rstrip("%") in allowed or _matches(tok, leaves):
            continue
        out.append(tok)
    return out


def _doc_text(doc: str) -> str:
    return DOCS[doc].read_text(encoding="utf-8")


@pytest.mark.parametrize("doc", list(DOCS))
def test_document_exists(doc):
    assert DOCS[doc].is_file(), f"{doc} is missing"


@pytest.mark.parametrize("doc", list(DOCS))
def test_no_number_outside_the_summary(doc):
    bad = unexplained_numbers(doc, _doc_text(doc))
    assert not bad, f"{doc} contains numbers that are not in summary.json: {sorted(set(bad))}"


@pytest.mark.parametrize("doc", list(DOCS))
def test_pairs_and_intervals_exist_in_the_summary(doc):
    text = prose(_doc_text(doc))
    known = pairs()
    for a, b in re.findall(r"(?<![\w.])(\d+) of (?:the )?(\d+)(?![\w.])", text) + re.findall(r"(?<![\w.])(\d+)/(\d+)(?![\w.])", text):
        assert (int(a), int(b)) in known, f"{doc}: '{a} of {b}' is not a (k, n) pair in summary.json"
    known_iv = intervals()
    for lo, hi in re.findall(r"\[\s*(-?\d+\.\d+)\s*,\s*(-?\d+\.\d+)\s*\]", text):
        ok = any(abs(l - float(lo)) <= 0.5 * 10 ** -len(lo.split(".")[1]) + 1e-6 and abs(h - float(hi)) <= 0.5 * 10 ** -len(hi.split(".")[1]) + 1e-6
                 for l, h in known_iv)
        assert ok, f"{doc}: interval [{lo}, {hi}] is not in summary.json"


def test_the_checker_catches_a_made_up_number():
    assert unexplained_numbers("README.md", "recall was 0.8123 on 777 cases") == ["0.8123", "777"]
    assert unexplained_numbers("README.md", "dates 14 Nov 2026 and `code 999` and [x](a/999.md) are ignored") == []
    leaf = next(v for v in numeric_leaves() if 0 < v < 1)
    assert unexplained_numbers("README.md", f"a real one: {leaf:.3f}") == []


# --- links -------------------------------------------------------------------------------------------------------------
def _anchors(path: Path) -> set[str]:
    out = set()
    for line in path.read_text(encoding="utf-8").splitlines():
        m = re.match(r"#+\s+(.*)", line)
        if m:
            title = re.sub(r"`", "", m.group(1)).strip().lower()
            out.add(re.sub(r"\s", "-", re.sub(r"[^\w\s-]", "", title)))
    return out


@pytest.mark.parametrize("doc", list(DOCS) + ["docs/results/SUMMARY.md"])
def test_relative_links_resolve(doc):
    path = DOCS.get(doc) or REPO_ROOT / doc
    text = FENCE.sub(" ", path.read_text(encoding="utf-8"))
    links = re.findall(r"\]\(([^)\s]+)\)", text)
    assert links, f"{doc} has no links"
    for link in links:
        if re.match(r"[a-z]+://|mailto:", link):
            continue
        target, _, anchor = link.partition("#")
        dest = path if not target else (path.parent / target)
        assert dest.exists(), f"{doc}: broken link {link}"
        if anchor and dest.suffix == ".md":
            assert anchor in _anchors(dest), f"{doc}: no heading for anchor #{anchor} in {dest.name}"


# --- wording limits from the supervisor reviews (CP3 to CP7b) --------------------------------------------------------------
NEGATION = re.compile(r"\b(not|never|no|neither|nor|without|isn't|cannot|can't|nothing|does not)\b", re.I)


@pytest.mark.parametrize("doc", list(DOCS))
def test_reachability_not_exploitability(doc):
    text = _doc_text(doc)
    assert "reachability" in text.lower() and "exploitab" in text.lower()
    for line in text.splitlines():
        for word in re.findall(r"\b(?:exploitable|exploitability|vulnerable to attack)\b", line, re.I):
            assert NEGATION.search(line) or "reachability" in line.lower() or "from" in line.lower(), \
                f"{doc}: '{word}' is used without a negation: {line.strip()[:120]}"


@pytest.mark.parametrize("doc", list(DOCS))
def test_adjudication_is_never_called_ground_truth(doc):
    for line in _doc_text(doc).splitlines():
        if re.search(r"ground truth", line, re.I):
            assert NEGATION.search(line) or re.search(r"by construction|known truth", line, re.I), \
                f"{doc}: 'ground truth' without a negation: {line.strip()[:140]}"


FINAL_REQUIRED = ["needs a human look", "BM25", "go1.26.10", "two Claude", "govulncheck", "not worse", "owner spot-check",
                  "candidate level", "does not beat", "false NOT_REACHABLE"]
NOTES_REQUIRED = ["needs a human look", "BM25", "two Claude", "govulncheck", "not worse"]


@pytest.mark.parametrize("doc,needles", [("docs/FINAL_REPORT.md", FINAL_REQUIRED), ("docs/INTERVIEW_NOTES.md", NOTES_REQUIRED)])
def test_required_caveats_are_present(doc, needles):
    text = _doc_text(doc)
    for n in needles:
        assert n.lower() in text.lower(), f"{doc} must contain '{n}' (a wording limit from the reviews)"


def test_readme_states_the_reachable_caveat():
    text = _doc_text("README.md")
    assert "needs a human look" in text
    assert "never exploitability" in text.lower() or "not exploitability" in text.lower()


def test_negative_results_are_stated_with_their_consequence():
    """Acceptance 3: each negative result appears in the final report next to what it changed in the design."""
    text = _doc_text("docs/FINAL_REPORT.md")
    for heading in ("E1", "HyDE", "agent", "REACHABLE paths"):
        assert re.search(rf"^#+ .*{heading}", text, re.M | re.I) or heading.lower() in text.lower(), heading
    assert text.lower().count("what it changed") >= 5
