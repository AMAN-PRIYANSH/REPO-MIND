"""Generate the committed results documents in docs/results/ from score report files.

Every number and table cell comes from the report JSON. The only hand-written text
is the per-case explanation prose in docs/results/notes/*.json, which is inserted
only for cases the data marks as needing one, and is labelled as hand-written.
"""

import json
from pathlib import Path
from typing import Any

from vulntrace.paths import REPO_ROOT

NOTES_DIR = REPO_ROOT / "docs" / "results" / "notes"
MISSING_NOTE = "**NO EXPLANATION RECORDED** (add one to the notes file)"


def load_notes(name: str, notes_dir: Path = NOTES_DIR) -> dict[str, str]:
    p = Path(notes_dir) / f"{name}.json"
    if not p.is_file():
        return {}
    return json.loads(p.read_text(encoding="utf-8"))["case_notes"]


def _env_lines(run: dict[str, Any] | None) -> list[str]:
    if not run:
        return ["(the report file has no `run` section; environment unknown)"]
    return [
        f"- OS: `{run.get('os')}`",
        f"- Python: `{run.get('python')}`",
        f"- Go: `{run.get('go')}`",
        f"- Repository commit at run time: `{run.get('repo_commit')}`"
        + (" (working tree had uncommitted changes)" if run.get("repo_dirty") else ""),
    ]


def cp1_cases_needing_notes(report: dict[str, Any]) -> list[str]:
    """Mismatches with truth, plus cases whose result changes when inlining is enabled."""
    ids = [c["id"] for c in report["cases"] if c["outcome"] != "AGREE"]
    for row in report.get("inlining_comparison", []):
        off = [r["result"] for r in row["inlining_disabled"]]
        on = [r["result"] for r in row["inlining_enabled"]]
        if off != on and row["id"] not in ids:
            ids.append(row["id"])
    return ids


def render_cp1_doc(report: dict[str, Any], notes: dict[str, str], source: str) -> str:
    c, env = report["counts"], report["environment"]
    lines = [
        "# CP1 results: linker presence on the synthetic suite",
        "",
        f"Generated by `python -m vulntrace results render --doc cp1` from `{source}`. Do not edit by hand.",
        "",
        "## Environment",
        "",
        *_env_lines(report.get("run")),
        f"- Go reported by the method: `{env['go_version']}` {env['goos']}/{env['goarch']}",
        "- Go environment for every build: `GOTOOLCHAIN=local`, `CGO_ENABLED=0`, `GOPROXY=off`, `GOFLAGS` unset",
        "",
        "## Commands",
        "",
        "```",
        (report.get("run") or {}).get("command", "python -m vulntrace fixtures score --method linker --compare-inlining"),
        f"python -m vulntrace results render --doc cp1 --input {source} --out docs/results/CP1_LINKER_RESULTS.md",
        "```",
        "",
        "## Per-case results (inlining disabled, used for scoring)",
        "",
        f"Build flags `{' '.join(report['build_flags'])}`. {report['scoring_note']}",
        "",
        "| Case | Category | Truth | Linker result | Scored as | Outcome | Matched binary symbols |",
        "|---|---|---|---|---|---|---|",
    ]
    for case in report["cases"]:
        res = ",".join(r["result"] for r in case["method_results"])
        errs = ",".join((r["error"] or {}).get("code", "") for r in case["method_results"] if r["error"])
        matched = "; ".join(s for r in case["method_results"] for s in r["details"]["matched_binary_symbols"]) or "-"
        lines.append(f"| {case['id']} | {case['category']} | {case['truth']} | {res}{f' ({errs})' if errs else ''} | "
                     f"{case['predicted']} | {case['outcome']} | {matched} |")
    lines += [
        "",
        f"Cases: {c['cases']}. Agreements: {c['agreements']}. False NOT_REACHABLE: {c['false_not_reachable']}. "
        f"False REACHABLE: {c['false_reachable']}. Errors: {c['errors']}.",
    ]
    if "inlining_comparison" in report:
        lines += ["", "## Inlining comparison", "", "Only the inlining-disabled column is used for scoring.", "",
                  "| Case | Truth | Inlining disabled (`-gcflags=all=-l`) | Inlining enabled (default) |",
                  "|---|---|---|---|"]
        for row in report["inlining_comparison"]:
            off = ",".join(r["result"] for r in row["inlining_disabled"])
            on = ",".join(r["result"] for r in row["inlining_enabled"])
            lines.append(f"| {row['id']} | {row['truth']} | {off} | {on} |")
    lines += ["", "## Mismatches and inlining flips, explained", "",
              "The case list is computed from the data; the explanation text is hand-written "
              "(`docs/results/notes/cp1_linker.json`) from reading the fixture code.", ""]
    needing = cp1_cases_needing_notes(report)
    if not needing:
        lines.append("None.")
    for cid in needing:
        lines.append(f"- `{cid}`: {notes.get(cid, MISSING_NOTE)}")
    extra = [k for k in notes if k not in needing]
    if extra:
        lines += ["", "## Other observations (hand-written)", ""]
        lines += [f"- `{k}`: {notes[k]}" for k in extra]
    return "\n".join(lines) + "\n"




CP2_FILES = {"R1": "naive_score.json", "R2": "linker_score.json", "R3": "vta_score.json", "R4": "combined_score.json"}
CP2_LABELS = {"R1": "Naive name-only graph (control)", "R2": "Linker presence", "R3": "VTA call graph",
              "R4": "Combined verdict (VTA + linker)"}


def _cell(results: list[dict[str, Any]]) -> str:
    return ",".join(r["result"] + (f" ({r['error']['code']})" if r["error"] else "") for r in results)


def load_cp2_reports(input_dir: Path) -> dict[str, dict[str, Any]]:
    reports = {k: json.loads((Path(input_dir) / f).read_text(encoding="utf-8")) for k, f in CP2_FILES.items()}
    ids = [[c["id"] for c in r["cases"]] for r in reports.values()]
    if any(i != ids[0] for i in ids):
        raise ValueError("the four score reports do not cover the same cases in the same order")
    return reports


def cp2_cases_needing_notes(reports: dict[str, dict[str, Any]]) -> list[str]:
    """Any single-method mismatch or error with truth, and every combined CANT_DETERMINE."""
    out = []
    for i, case in enumerate(reports["R4"]["cases"]):
        if case["outcome"] != "AGREE" or any(reports[k]["cases"][i]["outcome"] != "AGREE" for k in ("R1", "R2", "R3")):
            out.append(case["id"])
    return out


def _path_text(path: dict[str, Any] | None) -> str:
    if not path:
        return "-"
    parts = [path["entry"]["symbol"]]
    for e in path["edges"]:
        name = e["callee"].rsplit("/", 1)[-1]
        parts.append(name + (" [DYNAMIC]" if e["kind"] == "DYNAMIC" else ""))
    return " → ".join(parts)


def cp2_comparable_lines(doc: str) -> list[str]:
    """Table and count lines of a CP2 document that do not depend on timing or memory."""
    head = doc.split("## Helper resources")[0]
    return [ln for ln in head.splitlines() if ln.startswith("|") or ln.startswith("Combined `CANT_DETERMINE`")]


def render_cp2_doc(reports: dict[str, dict[str, Any]], notes: dict[str, str], source: str) -> str:
    comb, vta = reports["R4"], reports["R3"]
    run = comb.get("run") or {}
    env = comb["environment"]
    lines = [
        "# CP2 results: call graph, naive control and verdict rule on the synthetic suite",
        "",
        f"Generated by `python -m vulntrace results render --doc cp2` from `{source}/`. Do not edit by hand.",
        "",
        "## Environment",
        "",
        *_env_lines(run),
        f"- Helper toolchain: `{env.get('go_version')}` {env.get('goos')}/{env.get('goarch')}, "
        f"golang.org/x/tools `{env.get('x_tools_version')}`",
        "- Go environment for builds and package loading: `GOTOOLCHAIN=local`, `CGO_ENABLED=0`, `GOPROXY=off`, "
        "`GOFLAGS` unset",
        "- Verifier: not run in CP2 (`verification.status = NOT_RUN`); the rule's \"verifier passes\" column is "
        "treated as not yet applicable.",
        "",
        "## Commands",
        "",
        "```",
        *[(reports[k].get("run") or {}).get("command", f"(no run record in {CP2_FILES[k]})") for k in ("R1", "R2", "R3", "R4")],
        f"python -m vulntrace results render --doc cp2 --input {source} --out docs/results/CP2_CALLGRAPH_RESULTS.md",
        "```",
        "",
        "Repository commit of each run: "
        + ", ".join(f"{k} `{(reports[k].get('run') or {}).get('repo_commit')}`"
                    + (" (dirty)" if (reports[k].get("run") or {}).get("repo_dirty") else "") for k in CP2_FILES) + ".",
        "",
        "## Summary (false NOT_REACHABLE first)",
        "",
        "| Experiment | Method | Cases | False NOT_REACHABLE | False REACHABLE | Agreements | CANT_DETERMINE | Errors |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for k in ("R1", "R2", "R3", "R4"):
        c = reports[k]["counts"]
        lines.append(f"| {k} | {CP2_LABELS[k]} | {c['cases']} | {c['false_not_reachable']} | {c['false_reachable']} | "
                     f"{c['agreements']} | {c.get('cant_determine', 0)} | {c['errors']} |")
    by_reason = comb["counts"].get("cant_determine_by_reason", {})
    lines += [
        "",
        "Single methods never abstain: their `ERROR` results are counted as errors. The combined verdict turns every "
        "error into `CANT_DETERMINE` / `ANALYSIS_FAILED`, so it has no errors column of its own.",
        "",
        "Combined `CANT_DETERMINE` by reason code: "
        + (", ".join(f"`{k}` {v}" for k, v in by_reason.items()) or "none") + ".",
        "",
        "Combined verdict against truth (rows: truth; columns: verdict):",
        "",
        "| Truth | REACHABLE | NOT_REACHABLE | CANT_DETERMINE |",
        "|---|---|---|---|",
    ]
    for truth in ("REACHABLE", "NOT_REACHABLE"):
        row = comb["confusion"][truth]
        lines.append(f"| {truth} | {row['REACHABLE']} | {row['NOT_REACHABLE']} | {row['CANT_DETERMINE']} |")
    lines += [
        "",
        "These are hand-built cases with truth known by construction. They show where each method breaks; "
        "they are not an accuracy estimate.",
        "",
        "## Per-case results",
        "",
        "| Case | Category | Truth | R1 naive | R2 linker | R3 VTA | R4 verdict | Reason codes |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i, case in enumerate(comb["cases"]):
        n, ln, v = (reports[k]["cases"][i]["method_results"] for k in ("R1", "R2", "R3"))
        lines.append(f"| {case['id']} | {case['category']} | {case['truth']} | {_cell(n)} | {_cell(ln)} | {_cell(v)} | "
                     f"{case['predicted']} | {', '.join(case['reason_codes']) or '-'} |")
    lines += ["", "## VTA shortest paths", "",
              "First shortest path per case (`[DYNAMIC]`: interface or function-value call resolved by VTA). "
              "Package prefixes are shortened to the last path element.", "",
              "| Case | Path |", "|---|---|"]
    for case in vta["cases"]:
        r = case["method_results"][0]
        if r["result"] == "PATH_FOUND":
            lines.append(f"| {case['id']} | {_path_text(r['details']['path'])} |")
    lines += ["", "## Helper resources (VTA `reach`, one helper run per case)", "",
              "Peak RSS is the helper process's own high-water mark (`VmHWM`, Linux only). Helper time is measured "
              "inside the helper (load, SSA, call graph, search); wall time adds process start-up.", "",
              "| Case | Packages loaded | Call-graph nodes | Call-graph edges | Helper time (ms) | Wall time (ms) | Peak RSS (MB) |",
              "|---|---|---|---|---|---|---|"]
    rows = []
    for case in vta["cases"]:
        r = case["method_results"][0]
        st = r["details"].get("stats")
        if st:
            rows.append((case["id"], st, r["duration_ms"]))
            rss = f"{st['peak_rss_kb'] / 1024:.0f}" if st["peak_rss_kb"] is not None else "n/a"
            lines.append(f"| {case['id']} | {st['packages_loaded']} | {st['callgraph_nodes']} | {st['callgraph_edges']} | "
                         f"{st['duration_ms']} | {r['duration_ms']} | {rss} |")
    if rows:
        cid, st, wall = max(rows, key=lambda x: (x[1]["callgraph_nodes"], x[0]))
        rss = f"{st['peak_rss_kb'] / 1024:.0f} MB" if st["peak_rss_kb"] is not None else "not measured"
        peak = max((x[1]["peak_rss_kb"] or 0) for x in rows) / 1024
        lines += ["", f"Largest fixture by call-graph size: `{cid}` ({st['callgraph_nodes']} nodes, "
                      f"{st['callgraph_edges']} edges): helper time {st['duration_ms']} ms, wall time {wall} ms, "
                      f"peak RSS {rss}. Highest peak RSS over all cases: {peak:.0f} MB."]
    lines += ["", "## Disagreements and mismatches, explained", "",
              "The case list and the per-method outcomes are computed from the data; the explanation text is "
              "hand-written (`docs/results/notes/cp2_callgraph.json`) from reading the fixture code and the "
              "observed paths.", ""]
    needing = cp2_cases_needing_notes(reports)
    for cid in needing:
        i = [c["id"] for c in comb["cases"]].index(cid)
        parts = [f"{k} {reports[k]['cases'][i]['outcome']}" for k in ("R1", "R2", "R3")]
        rc = ", ".join(comb["cases"][i]["reason_codes"])
        parts.append(f"R4 {comb['cases'][i]['predicted']}" + (f" ({rc})" if rc else ""))
        lines.append(f"- `{cid}` ({'; '.join(parts)}): {notes.get(cid, MISSING_NOTE)}")
    if not needing:
        lines.append("None.")
    extra = [k for k in notes if k not in needing]
    if extra:
        lines += ["", "## Other observations (hand-written)", ""]
        lines += [f"- `{k}`: {notes[k]}" for k in extra]
    return "\n".join(lines) + "\n"


def render(doc: str, input_path: Path) -> str:
    source = Path(input_path).as_posix()
    if doc == "cp1":
        return render_cp1_doc(json.loads(Path(input_path).read_text(encoding="utf-8")), load_notes("cp1_linker"), source)
    if doc == "cp2":
        return render_cp2_doc(load_cp2_reports(Path(input_path)), load_notes("cp2_callgraph"), source.rstrip("/"))
    raise ValueError(f"unknown results document: {doc}")
