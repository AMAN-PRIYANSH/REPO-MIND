def render(doc: str, input_path: Path) -> str:
    source = Path(input_path).as_posix()
    if doc == "cp1":
        return render_cp1_doc(json.loads(Path(input_path).read_text(encoding="utf-8")), load_notes("cp1_linker"), source)
    if doc == "cp2":
        return render_cp2_doc(load_cp2_reports(Path(input_path)), load_notes("cp2_callgraph"), source.rstrip("/"))
    if doc == "cp3":
        return render_cp3_doc_from_dir(Path(input_path), source.rstrip("/"))
    if doc == "cp4":
        from vulntrace.eval.retrieval_report import render_cp4_doc

        return render_cp4_doc(Path(input_path), source.rstrip("/"))
    if doc == "cp5":
        from vulntrace.eval.llm_report import render_cp5_doc

        return render_cp5_doc(Path(input_path), source.rstrip("/"))
    if doc == "cp5b":
        from vulntrace.eval.lift_report import render_cp5b_doc

        return render_cp5b_doc(Path(input_path), source.rstrip("/"))
    if doc == "cp6":
        from vulntrace.eval.agent_report import render_cp6_doc

        return render_cp6_doc(Path(input_path), source.rstrip("/"))
    if doc == "cp7":
        from vulntrace.eval.triage_report import render_cp7_doc

        return render_cp7_doc(Path(input_path), source.rstrip("/"))
    raise ValueError(f"unknown results document: {doc}")


def render_cp3_doc_from_dir(score_dir: Path, source: str) -> str:
    from vulntrace.dataset import build as dataset_build
    from vulntrace.dataset import ceiling as ceiling_mod
    from vulntrace.dataset import datasets

    d1 = json.loads((dataset_build.RESULTS_DATASETS_DIR / "D1_cases.json").read_text(encoding="utf-8"))
    d4 = json.loads((dataset_build.RESULTS_DATASETS_DIR / "D4_cases.json").read_text(encoding="utf-8"))
    e0 = json.loads((Path(score_dir) / "e0_score.json").read_text(encoding="utf-8"))
    id_search = json.loads((Path(score_dir) / "id_search_score.json").read_text(encoding="utf-8"))

    cases, _ = datasets.load_all_cases()
    cases_by_id = {c["id"]: c for c in cases}
    rr_dir = dataset_build.DATA_DIR / "release_range"
    release_ranges_by_id = {}
    for c in d4["cases"]:
        p = rr_dir / f"{c['id']}.json"
        if p.is_file():
            release_ranges_by_id[c["id"]] = json.loads(p.read_text(encoding="utf-8"))
    ceiling_result = ceiling_mod.run_investigation(cases_by_id, release_ranges_by_id)
    materialized = {}
    for name in ("D1", "D4"):
        mp = dataset_build.RESULTS_DATASETS_DIR / f"{name}_materialize.json"
        if mp.is_file():
            materialized[name] = json.loads(mp.read_text(encoding="utf-8"))
    return render_cp3_doc(d1, d4, e0, id_search, ceiling_result, source, materialized)
