"""`python -m vulntrace cp9 report`: render docs/results/CP9_FEASIBILITY_RESULTS.md from the
committed files under docs/results/cp9/ (CP9 deliverable 4).

The headline sentence below was fixed and committed before any D3b result existed (see git
history of this file); it is filled from the scored D3b adjudication and not edited after. Before
the adjudication is filled, the document says the headline is pending and shows nothing about D3b
that would need truth.
"""

import json
from pathlib import Path
from typing import Any

from vulntrace.eval.triage_eval import wilson
from vulntrace.paths import REPO_ROOT

RESULTS = REPO_ROOT / "docs" / "results" / "cp9"
OUT = REPO_ROOT / "docs" / "results" / "CP9_FEASIBILITY_RESULTS.md"

# Fixed before any D3b result (CP9 specification, deliverable 4). Do not edit.
HEADLINE = ("On the held-out set D3b ({apps} real Go applications, {cases} cases), the path-feasibility filter "
            "downgraded {down} of {reach_off} REACHABLE verdicts to CANT_DETERMINE; adjudicated REACHABLE path "
            "precision was {prec_off} without the filter and {prec_on} with it, and {misses} of {down_adj} "
            "downgraded cases were judged reachable by some path (the filter's misses).")
HEADLINE_PENDING = "Headline pending: the D3b adjudication is not filled yet (state AWAITING_ADJUDICATION)."

PRECISION_LABELS = ("CORRECT", "INFEASIBLE_PATH", "WRONG")


def rate(k: int, n: int) -> str:
    if n == 0:
        return "n/a (n = 0)"
    w = wilson(k, n)
    return f"{k}/{n} = {k / n:.2f} [95% Wilson {w['ci_low']:.2f} to {w['ci_high']:.2f}]"


def precision(labels: list[str | None]) -> tuple[int, int]:
    judged = [x for x in labels if x in PRECISION_LABELS]
    return sum(1 for x in judged if x == "CORRECT"), len(judged)


def d3b_scores(rows: list[dict[str, Any]], sheet: dict[str, Any] | None) -> dict[str, Any] | None:
    """From the filled D3b sheet (None until it is filled): the headline numbers."""
    if not sheet or not all(c.get("filled") for c in sheet.get("cases") or []):
        return None
    by_id = {c["id"]: c for c in sheet["cases"]}
    reach_off = [r for r in rows if r["verdict_off"] == "REACHABLE"]
    reach_on = [r for r in rows if r["verdict_on"] == "REACHABLE"]
    down = [r for r in rows if r["downgraded_by_filter"]]
    off_labels = [by_id[r["id"]].get("adjudication_off") for r in reach_off]
    on_labels = []
    for r in reach_on:
        c = by_id[r["id"]]
        on_labels.append(c.get("adjudication_off") if c.get("adjudication_on") == "SAME_AS_OFF" else c.get("adjudication_on"))
    down_truth = [by_id[r["id"]].get("truth") for r in down]
    k_off, n_off = precision(off_labels)
    k_on, n_on = precision(on_labels)
    misses = sum(1 for t in down_truth if t == "REACHABLE")
    judged = sum(1 for t in down_truth if t in ("REACHABLE", "NOT_REACHABLE"))
    apps = len({r["app_repo"] for r in rows})
    return {"apps": apps, "cases": len(rows), "down": len(down), "reach_off": len(reach_off),
            "prec_off": rate(k_off, n_off), "prec_on": rate(k_on, n_on), "misses": misses, "down_adj": judged,
            "misses_rate": rate(misses, judged)}


def headline(scores: dict[str, Any] | None) -> str:
    return HEADLINE_PENDING if scores is None else HEADLINE.format(**scores)


def _load(name: str) -> Any:
    p = RESULTS / name
    return json.loads(p.read_text(encoding="utf-8")) if p.is_file() else None


def render() -> str:
    """The results document (sections appear as their result files exist)."""
    fx = _load("fixtures.json")
    d3 = _load("d3/d3_feasibility.json")
    d3b = _load("d3b/d3b_feasibility.json")
    sheet = _load("d3b/adjudication/adjudication.json")
    d1, d4 = _load("d1_feasibility.json"), _load("d4_feasibility.json")
    scores = d3b_scores(d3b["rows"], sheet) if d3b else None
    out = ["# CP9 results: path-feasibility filter for REACHABLE (downgrade-only)", "",
           "Generated by `python -m vulntrace cp9 report` from committed files under `docs/results/cp9/`; do not edit by hand.",
           "", "## Headline", "", headline(scores), "",
           "The filter only turns REACHABLE into CANT_DETERMINE (reason PATHS_INFEASIBLE); it never makes NOT_REACHABLE "
           "and never makes anything stronger. REACHABLE still means a call-graph path exists, not exploitability.", ""]
    out += render_fixtures(fx) + render_d3(d3) + render_d3b(d3b, scores) + render_dist("D1", d1) + render_dist("D4", d4)
    return "\n".join(out).rstrip() + "\n"


def _md(x: Any) -> str:
    return str(x).replace("|", "\\|").replace("\n", " ")


def render_fixtures(fx: dict[str, Any] | None) -> list[str]:
    if not fx:
        return ["## Fixtures", "", "Not run yet.", ""]
    c = fx["cp9_fixtures"]
    out = ["## Fixtures (truth by construction)", "",
           f"CP9 fixtures (`fixtures/feasibility`, {len(c['rows'])} cases): by kind {_md(c['by_kind'])}.", "",
           f"- False downgrades of feasible look-alikes: **{len(c['false_downgrades'])}** {_md(c['false_downgrades'])}",
           f"- Cases not as constructed: {len(c['not_as_expected'])} {_md(c['not_as_expected'])}", "",
           "| case | pattern | kind | truth | off | on | filter | first infeasible steps |", "|---|---|---|---|---|---|---|---|"]
    for r in c["rows"]:
        out.append(f"| {r['id']} | {r['pattern']} | {r['kind']} | {r['truth']} | {r['verdict_off']} | {r['verdict_on']} | "
                   f"{r['filter_status']} | {_md(', '.join(r['first_patterns']) or '-')} |")
    rep, old = fx["cp7_reproduction"], fx["cp7_fixtures_with_filter"]
    out += ["", f"CP2/CP7 fixtures ({old['rows']} runs, 22 cases x 3 modes): verdicts changed by the filter "
            f"{len(old['changed'])}, false downgrades of truly REACHABLE runs **{len(old['false_downgrades'])}** "
            f"(of {old['true_reachable_rows_checked']} REACHABLE runs).",
            f"`--no-feasibility` against the committed CP7 results: rows compared {rep['rows_compared']}, differences "
            f"{len(rep['differences'])}, corruption probe equal {rep['corruption_probe_equal']}, summaries equal (timings "
            f"excluded) {rep['summary_equal_except_seconds']}: identical = **{rep['identical']}**.", ""]
    return out


def render_d3(d3: dict[str, Any] | None) -> list[str]:
    if not d3:
        return ["## D3 (in-sample)", "", "Not run yet.", ""]
    s = d3["summary"]
    out = ["## D3 before/after (IN-SAMPLE, not evidence of generalisation)", "", d3["label"], "",
           f"Cases {s['cases']}, REACHABLE without the filter {s['reachable_off']}, downgraded by the filter "
           f"{len(s['downgraded_cases'])} {_md(s['downgraded_cases'])}; REACHABLE entries {s['reachable_entries']}, "
           f"filter answers {_md(s['entry_statuses'])}, deciding patterns {_md(s['deciding_patterns_of_infeasible_entries'])}.", ""]
    rep = d3.get("cp7b_reproduction") or {}
    out += [f"`--no-feasibility` against the committed CP7b verdicts: compared {rep.get('compared')}, identical "
            f"{len(rep.get('identical') or [])}, different {len(rep.get('different') or [])}, missing "
            f"{len(rep.get('missing') or [])}.", "",
            "| case | CP7b adjudication | off | on | filter answers | first infeasible step (shortest path) |",
            "|---|---|---|---|---|---|"]
    adj = d3.get("cp7b_adjudication") or {}
    for r in d3["rows"]:
        steps = [st for e in r["reachable_entries"] for st in e["steps"][:1]]
        first = f"{steps[0]['pattern']} at {steps[0]['site']['file']}:{steps[0]['site']['line']}" if steps else "-"
        out.append(f"| {r['id']} | {(adj.get(r['id']) or {}).get('adjudication')} | {r['verdict_off']} | {r['verdict_on']} | "
                   f"{_md(r['filter_statuses'] or '-')} | {_md(first)} |")
    return out + [""]


def render_d3b(d3b: dict[str, Any] | None, scores: dict[str, Any] | None) -> list[str]:
    if not d3b:
        return ["## D3b (held-out)", "", "Not run yet.", ""]
    s = d3b["summary"]
    out = ["## D3b before/after (held-out)", "",
           f"Cases {s['cases']}, REACHABLE without the filter {s['reachable_off']}, downgraded {len(s['downgraded_cases'])}; "
           f"filter answers {_md(s['entry_statuses'])}.", ""]
    if scores is None:
        out += ["Adjudication pending: no precision or miss numbers are shown before the sheet is filled.", ""]
    else:
        out += [f"- REACHABLE path precision without the filter: {scores['prec_off']}",
                f"- REACHABLE path precision with the filter: {scores['prec_on']}",
                f"- downgraded cases judged reachable by some path (misses): {scores['misses_rate']}", ""]
    return out


def render_dist(name: str, d: dict[str, Any] | None) -> list[str]:
    if not d:
        return [f"## {name} distribution", "", "Not run yet.", ""]
    s = d["summary"]
    return [f"## {name}: downgrades by pattern (cost of the filter; no truth)", "", d["note"], "",
            f"Re-run {s['rerun']} of the CP7 REACHABLE cases; filter off reproduced CP7 in {s['reproduced_cp7']}; "
            f"REACHABLE without the filter {s['reachable_off']}; cases downgraded {s['downgraded']}. Per REACHABLE entry (one target "
            f"symbol from one main package) the filter answered {_md(s['entry_statuses'])}; INFEASIBLE entries by deciding "
            f"pattern {_md(s['entry_deciding_patterns'] or 'none')} (an INFEASIBLE entry leaves its case REACHABLE when another "
            f"entry of the case is FEASIBLE).", ""]


def write(out: Path = OUT) -> Path:
    out.write_text(render(), encoding="utf-8")
    return out
