# --- row helpers ---------------------------------------------------------------------------------------------
def _r(x: Any) -> Any:
    """A plain Python number (numpy scalars converted, NaN/inf -> None). Values are NOT rounded here: the results documents format the
    unrounded value to three decimals, and rounding twice can differ in the last digit. JSON output rounds once (see `dumps`)."""
    if x is None:
        return None
    if isinstance(x, (int, np.integer)) and not isinstance(x, bool):
        return int(x)
    x = float(x)
    return x if math.isfinite(x) else None


class _Reader:
    """Reads files below the repository root and remembers which ones were read."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.read: set[str] = set()

    def path(self, rel: str | Path) -> Path:
        self.read.add(str(rel))
        return self.root / rel

    def json(self, rel: str | Path) -> Any:
        return json.loads(self.path(rel).read_text(encoding="utf-8"))

    def sources(self) -> dict[str, str]:
        """sha256 of every file read (a directory that was listed stands for the JSON files below it)."""
        files: set[str] = set()
        for rel in self.read:
            p = self.root / rel
            if p.is_dir():
                files.update(str(q.relative_to(self.root)) for q in p.rglob("*.json"))
            else:
                files.add(rel)
        return {rel: hashlib.sha256((self.root / rel).read_bytes()).hexdigest() for rel in sorted(files)}


def _mean(rid, label, m, src, n_clusters=None, unit="") -> dict[str, Any]:
    return {"id": rid, "label": label, "kind": "mean", "value": _r(m["mean"]), "ci_low": _r(m["ci_low"]),
            "ci_high": _r(m["ci_high"]), "n": m.get("n"), "n_clusters": m.get("n_clusters", n_clusters), "source": src}


def _delta(rid, label, d, src, n_clusters=None) -> dict[str, Any]:
    out = _mean(rid, label, d, src, n_clusters)
    out["kind"] = "delta"
    out["reading"] = lr.verdict(d).split(" (")[0]
    return out


def _rate(rid, label, k, n, src) -> dict[str, Any]:
    w = wilson(k, n)
    return {"id": rid, "label": label, "kind": "rate", "k": k, "n": n, "value": _r(w["rate"]),
            "ci_low": _r(w["ci_low"]), "ci_high": _r(w["ci_high"]), "source": src}


def _count(rid, label, k, n, src) -> dict[str, Any]:
    return {"id": rid, "label": label, "kind": "count", "k": k, "n": n, "source": src}


def _value(rid, label, v, src, fmt="{:.1f}") -> dict[str, Any]:
    return {"id": rid, "label": label, "kind": "value", "value": _r(v), "fmt": fmt, "source": src}


def _wilson_row(rid, label, r, src) -> dict[str, Any]:
    """A rate already computed with Wilson intervals by the pipeline code (k, n, rate, ci_*)."""
    return {"id": rid, "label": label, "kind": "rate", "k": r["k"], "n": r["n"], "value": _r(r["rate"]),
            "ci_low": _r(r["ci_low"]), "ci_high": _r(r["ci_high"]), "source": src}


def _section(sid, title, question, rows, caveats, interval) -> dict[str, Any]:
    return {"id": sid, "title": title, "question": question, "interval": interval, "caveats": caveats, "rows": rows}


