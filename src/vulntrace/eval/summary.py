"""The results summary (CP8): `docs/results/SUMMARY.md` and `docs/results/summary.json`.

Every number here is computed from files committed under `docs/results/` by the same statistics code
that renders the per-checkpoint results documents (same seeds, same cluster bootstrap), so a headline
number here equals the number in the corresponding results document. Nothing is typed by hand: the only
literal text is the experiment titles, the question each experiment asked, and caveat sentences that
contain no result numbers. Each row names the result file(s) it came from, and `summary.json` records the
sha256 of every file read.

A row is one of:
  mean   a metric with a 95% cluster-bootstrap interval
  delta  a paired difference (first minus second) with a paired cluster-bootstrap interval
  rate   k of n with a 95% Wilson interval
  count  k of n, no interval
  value  a single derived number (a ratio or a mean) with no interval

`python -m vulntrace results summary` writes the two files and refreshes the key-results table between the
markers in the repository README. `--check` writes nothing and fails if a committed file differs.
"""

