# --- build / render -------------------------------------------------------------------------------------------
def build_summary(root: Path = REPO_ROOT) -> dict[str, Any]:
    rd = _Reader(root)
    sections = [_datasets(rd), _cp4(rd), _cp5(rd), _cp5b(rd), _cp6(rd), _cp7(rd), _cp7b(rd)]
    ids = [r["id"] for s in sections for r in s["rows"]]
    dup = [i for i, c in Counter(ids).items() if c > 1]
    if dup:
        raise ValueError(f"duplicate row ids: {dup}")
    go = sorted({rd.json(RESULTS / "cp5b/lift_d1.json")["environment"]["go"].split()[2][2:],
                 rd.json(RESULTS / "cp7b/d3_triage.json")["environment"]["go"].split()[2][2:],
                 rd.json(RESULTS / "cp7/d1.json")["environment"]["go"].split()[2][2:]})
    s1_k = sorted({int(r["id"].split(".k")[1].split(".")[0]) for r in sections[2]["rows"] if ".s1." in r["id"]}, reverse=True)
    # constants the prose may quote; they are not results
    parameters = {"interval_percent": 95, "s1_top_k_values": s1_k, "mode2_policy_min_raw_not_reachable": POLICY_MIN_NR,
                  "stability_cases_per_set": rd.json(RESULTS / "cp7/d1.json")["stability"]["cases"].__len__()}
    return {"schema_version": SCHEMA_VERSION, "generated_by": "python -m vulntrace results summary", "go_versions": go,
            "parameters": parameters, "sections": sections, "sources": rd.sources()}


def index_rows(summary: dict[str, Any]) -> dict[str, dict[str, Any]]:
    return {r["id"]: r for s in summary["sections"] for r in s["rows"]}


def _fmt(row: dict[str, Any]) -> str:
    k = row["kind"]
    ci = f" [{row['ci_low']:.3f}, {row['ci_high']:.3f}]" if row.get("ci_low") is not None else ""
    if k in ("mean", "delta"):
        return f"{row['value']:.3f}{ci}"
    if k == "rate":
        return f"{row['k']}/{row['n']} = {row['value']:.3f}{ci}"
    if k == "count":
        return f"{row['k']} of {row['n']}"
    return row["fmt"].format(row["value"])


def _links(row: dict[str, Any], from_dir: str) -> str:
    out = []
    for s in row["source"]:
        rel = os.path.relpath(s, from_dir).replace(os.sep, "/")
        out.append(f"[{os.path.basename(s) or s}]({rel})")
    return ", ".join(out)


def _n_cell(row: dict[str, Any]) -> str:
    if row["kind"] in ("mean", "delta") and row.get("n"):
        nc = row.get("n_clusters")
        return f"{row['n']} ({nc} clusters)" if nc else str(row["n"])
    return ""


def render_markdown(summary: dict[str, Any]) -> str:
    out = ["# Results summary", "",
           "Generated by `python -m vulntrace results summary` from the committed result files. Do not edit by hand. Every number is computed "
           "by code from the files named in its row, with the same statistics code that renders the per-checkpoint results documents; "
           "`summary.json` holds the same numbers and the sha256 of every file read.", "",
           "Reachability only: a verdict says whether a vulnerable function can be reached in the call graph from a `main` package, never whether "
           "the vulnerability can be exploited. Intervals are 95%; the interval type is stated per section. A paired difference is called better "
           "or worse only when its interval excludes zero.", "", "Contents: " + ", ".join(f"[{s['title']}](#{_anchor(s['title'])})" for s in summary["sections"]), ""]
    for s in summary["sections"]:
        out += [f"## {s['title']}", "", f"*Question:* {s['question']}", "", f"*Interval:* {s['interval']}.", "",
                "| Result | n | Value [95% interval] | Source |", "|---|---|---|---|"]
        for r in s["rows"]:
            out.append(f"| {r['label']} | {_n_cell(r)} | {_fmt(r)} | {_links(r, 'docs/results')} |")
        out += ["", "Caveats:", ""] + [f"- {c}" for c in s["caveats"]] + [""]
    return "\n".join(out).rstrip() + "\n"


def _anchor(title: str) -> str:
    keep = "".join(ch if (ch.isalnum() or ch in " -") else "" for ch in title.lower())
    return keep.strip().replace(" ", "-")


