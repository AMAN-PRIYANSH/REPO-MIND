def update_readme(text: str, summary: dict[str, Any]) -> str:
    if README_BEGIN not in text or README_END not in text:
        raise ValueError("README.md has no key-results markers")
    head, rest = text.split(README_BEGIN, 1)
    _, tail = rest.split(README_END, 1)
    return head + README_BEGIN + "\n" + key_results_markdown(summary) + "\n" + README_END + tail


JSON_DECIMALS = 6


def _round_floats(obj: Any) -> Any:
    if isinstance(obj, float):
        return round(obj, JSON_DECIMALS)
    if isinstance(obj, dict):
        return {k: _round_floats(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_round_floats(v) for v in obj]
    return obj


def dumps(summary: dict[str, Any]) -> str:
    return json.dumps(_round_floats(summary), indent=1, sort_keys=False, ensure_ascii=False) + "\n"


def expected_files(root: Path = REPO_ROOT) -> dict[Path, str]:
    """Path -> exact content of every generated file (README included when it has the markers)."""
    summary = build_summary(root)
    out = {Path("docs/results/summary.json"): dumps(summary), Path("docs/results/SUMMARY.md"): render_markdown(summary)}
    readme = root / "README.md"
    if readme.is_file() and README_BEGIN in readme.read_text(encoding="utf-8"):
        out[Path("README.md")] = update_readme(readme.read_text(encoding="utf-8"), summary)
    return out


def cmd_summary(args) -> int:
    root = Path(args.root) if getattr(args, "root", None) else REPO_ROOT
    files = expected_files(root)
    if args.check:
        bad = [str(p) for p, text in files.items() if not (root / p).is_file() or (root / p).read_text(encoding="utf-8") != text]
        for p in bad:
            print(f"out of date: {p}", flush=True)
        if bad:
            print("run: python -m vulntrace results summary", flush=True)
            return 1
        print("summary files are up to date", flush=True)
        return 0
    for p, text in files.items():
        (root / p).write_text(text, encoding="utf-8")
        print(f"wrote {p} ({len(text.encode('utf-8'))} bytes)", flush=True)
    return 0
