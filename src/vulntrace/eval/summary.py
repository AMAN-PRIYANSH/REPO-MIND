# --- CP4: retrieval ------------------------------------------------------------------------------------------
def _cp4(rd: _Reader) -> dict[str, Any]:
    d = RESULTS / "cp4"
    cases_doc = rd.json(d / "cases.json")
    files = sorted((rd.root / d / "runs").glob("*.json"))
    runs = [json.loads(p.read_text(encoding="utf-8")) for p in files]
    for p in files:
        rd.read.add(str(p.relative_to(rd.root)))
    ids = [c["id"] for c in cases_doc["cases"]]
    for r in runs:
        assert [row["id"] for row in r["rows"]] == ids
    s = rr.Summaries(cases_doc, runs)
    path = {i: str(p.relative_to(rd.root)) for i, p in enumerate(files)}
    src_c = str(d / "cases.json")

    def find(kind, variant=PRIMARY, config=None):
        i = rr._find(runs, kind, variant, config)
        assert i is not None, (kind, variant, config)
        return i

    rows: list[dict[str, Any]] = []
    spec = [("random", "random", "-", None), ("size", "size", "-", None), ("bid", "B-ID (commit-message identifier search)", "-", None),
            ("bm25", "BM25", PRIMARY, None), ("dense", "dense bge-small", PRIMARY, "dense:bge-small"),
            ("hybrid", "hybrid bge-small + BM25 (RRF)", PRIMARY, "hybrid:bge-small"),
            ("rerank_minilm", "hybrid + MiniLM cross-encoder rerank", PRIMARY, "hybrid+rerank:bge-small+minilm"),
            ("rerank_bge", "hybrid + bge-reranker rerank", PRIMARY, "hybrid+rerank:bge-small+bge-reranker"),
            ("dense_code", "dense code-search embedder (128-token limit)", PRIMARY, "dense:codesearch")]
    idx: dict[str, int] = {}
    for key, label, variant, config in spec:
        kind = {"rerank_minilm": "hybrid+rerank", "rerank_bge": "hybrid+rerank", "dense_code": "dense"}.get(key, key)
        i = find(kind, variant, config)
        idx[key] = i
        sm = s.summary(i)
        rows.append(_mean(f"cp4.mrr.{key}", f"MRR, all scored cases: {label}", sm["mrr"], [path[i], src_c]))
        rows.append(_mean(f"cp4.r10.{key}", f"Recall@10, all scored cases: {label}", sm["recall@10"], [path[i], src_c]))
    for key in ("bid", "bm25", "dense", "hybrid"):
        i = idx[key]
        rows.append(_mean(f"cp4.mrr_large.{key}", f"MRR, cases with more than 100 candidates: {dict((k, l) for k, l, *_ in spec)[key]}",
                          s.summary(i, "size:>100")["mrr"], [path[i], src_c]))
    for label, a, b in (("dense vs BM25", "dense", "bm25"), ("hybrid vs BM25", "hybrid", "bm25"), ("hybrid vs dense", "hybrid", "dense"),
                        ("dense vs B-ID", "dense", "bid"), ("MiniLM rerank vs hybrid", "rerank_minilm", "hybrid"),
                        ("bge-reranker rerank vs hybrid", "rerank_bge", "hybrid"),
                        ("code-search embedder vs bge-small (dense)", "dense_code", "dense")):
        rows.append(_delta(f"cp4.d_mrr.{a}_vs_{b}", f"Paired MRR difference: {label}", s.paired_diff(idx[a], idx[b], "mrr"),
                           [path[idx[a]], path[idx[b]], src_c]))
    # commit subjects in the chunk text
    for kind, cfg, key in (("hybrid", "hybrid:bge-small", "hybrid"), ("bm25", "bm25", "bm25")):
        a, b = find(kind, PRIMARY, cfg), find(kind, "code_only", cfg)
        rows.append(_delta(f"cp4.d_mrr.commits_{key}", f"Paired MRR difference: commit subjects in the chunk text vs code only ({key})",
                           s.paired_diff(a, b, "mrr"), [path[a], path[b], src_c]))
    a, b = find("hybrid", PRIMARY, "hybrid:bge-small"), find("hybrid", "code+commits_idmasked", "hybrid:bge-small")
    rows.append(_delta("cp4.d_mrr.idmask_hybrid", "Paired MRR difference: advisory IDs masked vs not (hybrid, the control)",
                       s.paired_diff(b, a, "mrr"), [path[a], path[b], src_c]))
    n_all = int(len(cases_doc["cases"]))
    in_cand = int(s.denom_mask("a").sum())
    rows.append(_count("cp4.gold_in_candidates", "Scored cases whose labelled function is among the candidates", in_cand, n_all, [src_c]))
    rows.append(_count("cp4.runs", "Retrieval runs compared", len(runs), len(runs), [str(d / "runs")]))
    return _section("cp4", "CP4: Mode 2 retrieval on D4",
                    "Do hybrid search and reranking find the vulnerable function among a release range's changed functions better than "
                    "simple baselines?", rows,
                    ["BM25, dense and hybrid retrieval are statistically indistinguishable on this data; the paired intervals include zero.",
                     "Rerankers do not help; the code-search embedder is worse than bge-small.",
                     "Retrieval only ranks the candidates a range contains; it cannot recover a labelled function that is not a candidate.",
                     "The advisory-ID control is weak: no query contains an advisory ID."],
                    "cluster-bootstrap (D4 ranges)")


# --- CP5: E1, S1, HyDE ----------------------------------------------------------------------------------------
def _cp5(rd: _Reader) -> dict[str, Any]:
    d = RESULTS / "cp5"
    res = lr.load_dir(rd.path(d))
    for p in sorted((rd.root / d).rglob("*.json")):
        rd.read.add(str(p.relative_to(rd.root)))
    rows: list[dict[str, Any]] = []
    for alias, doc in res["e1"].items():
        src = [f"docs/results/cp5/select_fix__{alias}.json"]
        cell = lr._headline_cell(doc["rows"], doc["model"]["cutoff"], "llm", "e0")
        n, nc, dd, sm, sb = cell
        rows += [
            _mean(f"cp5.e1.{alias}.recall", f"E1 recall, LLM `{alias}` (post-cutoff headline group)", sm["recall"], src),
            _mean(f"cp5.e1.{alias}.recall_e0", f"E1 recall, E0 baseline (every changed function), same cases", sb["recall"], src),
            _mean(f"cp5.e1.{alias}.f1", f"E1 F1, LLM `{alias}`", sm["f1"], src),
            _mean(f"cp5.e1.{alias}.f1_e0", "E1 F1, E0 baseline", sb["f1"], src),
            _delta(f"cp5.e1.{alias}.d_recall", f"E1 paired recall difference, LLM `{alias}` minus E0", dd["recall"], src),
            _delta(f"cp5.e1.{alias}.d_f1", f"E1 paired F1 difference, LLM `{alias}` minus E0", dd["f1"], src),
            _delta(f"cp5.e1.{alias}.d_anyhit", f"E1 paired any-hit difference, LLM `{alias}` minus E0", dd["any_hit"], src),
            _delta(f"cp5.e1.{alias}.d_precision", f"E1 paired precision difference, LLM `{alias}` minus E0", dd["precision0"], src),
        ]
        for r in rows[-8:]:
            r["n"], r["n_clusters"] = n, nc
    for (alias, k), doc in res["s1"].items():
        src = [f"docs/results/cp5/select_release__{alias}__k{k}.json"]
        sub = [r for r in doc["rows"] if r["gold_in_topk"]]
        cell = lr._headline_cell(sub, doc["model"]["cutoff"], "llm", "top1")
        n, nc, dd, sm, sb = cell
        asked = [r for r in doc["rows"] if r["llm"]["status"] != "NOT_ASKED"]
        abst = [r for r in asked if r["llm"]["status"] == "VALID" and r["llm"]["abstain"]]
        rows += [
            _mean(f"cp5.s1.{alias}.k{k}.anyhit", f"S1 any-hit, LLM `{alias}` choosing from the top-{k}", sm["any_hit"], src),
            _mean(f"cp5.s1.{alias}.k{k}.top1", f"S1 any-hit, retriever top-1, same cases (top-{k})", sb["any_hit"], src),
            _delta(f"cp5.s1.{alias}.k{k}.d_anyhit", f"S1 paired any-hit difference, LLM `{alias}` minus retriever top-1 (top-{k})", dd["any_hit"], src),
            _count(f"cp5.s1.{alias}.k{k}.abstained", f"S1 cases where `{alias}` abstained (top-{k}, all asked cases)", len(abst), len(asked), src),
        ]
        for r in rows[-4:-1]:
            r["n"], r["n_clusters"] = n, nc
    for alias, h in res["hyde"].items():
        cutoff = h["meta"]["model"]["cutoff"]
        created = {r["id"]: r["created"] for r in h["meta"]["rows"]}
        facts = [{**c, "date_bucket": contamination_bucket(created.get(c["id"]), cutoff)} for c in h["cases"]["cases"]]
        s = rr.Summaries({**h["cases"], "cases": facts}, h["runs"])
        group = "date:post" if cutoff else f"date:{BUCKET_POSSIBLY_SEEN}"
        main_cfg = h["meta"]["retriever"]["config"]
        by: dict[str, dict[str, int]] = {}
        for i, r in enumerate(h["runs"]):
            by.setdefault(r["config"], {})[r["hyde"]] = i
        src = [f"docs/results/cp5/hyde__{alias}/runs", f"docs/results/cp5/hyde__{alias}/hyde_meta.json"]
        i0, i1 = by[main_cfg]["query"], by[main_cfg]["query+hyde"]
        rows += [
            _mean(f"cp5.hyde.{alias}.mrr_plain", f"HyDE MRR, plain query ({main_cfg}), `{alias}` headline group", s.summary(i0, group)["mrr"], src),
            _mean(f"cp5.hyde.{alias}.mrr_hyde", f"HyDE MRR, query + HyDE ({main_cfg}), `{alias}`", s.summary(i1, group)["mrr"], src),
            _delta(f"cp5.hyde.{alias}.d_mrr", f"HyDE paired MRR difference, query + HyDE minus plain query ({main_cfg}), `{alias}`",
                   s.paired_diff(i1, i0, "mrr", group), src),
        ]
        groups = [("date:post" if cutoff else f"date:{BUCKET_POSSIBLY_SEEN}"), *(["date:pre"] if cutoff else []), "date:undated", "all"]
        n_cmp = n_excl = 0
        for g in groups:
            for dn in ("b", "a"):
                if not int((s.group_mask(g) & s.denom_mask(dn)).sum()):
                    continue
                for cfg, vs in by.items():
                    base = vs.get("query")
                    for v in ("query+hyde", "hyde-only"):
                        if v in vs and base is not None:
                            dm = s.paired_diff(vs[v], base, "mrr", g, dn)
                            n_cmp += 1
                            n_excl += int(bool(dm.get("n")) and (dm["ci_low"] > 0 or dm["ci_high"] < 0))
        rows.append(_count(f"cp5.hyde.{alias}.excl", f"HyDE MRR comparisons whose paired interval excludes 0, `{alias}` (of all comparisons made, uncorrected)",
                           n_excl, n_cmp, src))
    return _section("cp5", "CP5: LLM selection (E1, S1) and HyDE",
                    "Does a local LLM improve on (E1) predicting every changed function of a fix commit, (S1) the retriever's top-1, "
                    "and does a hypothetical-document query (HyDE) improve retrieval?", rows,
                    ["E1: choosing one function from a fix diff lowers recall against the baseline that keeps all of them; a wrong narrowing is "
                     "the error that could cause a false NOT_REACHABLE later.",
                     "S1: one model improves on top-1 only when it answers; the other abstains often because the frozen prompt invites abstention; "
                     "this measures instruction following, not code understanding.",
                     "HyDE: at most one of many comparisons excludes zero, with no correction for multiple comparisons; not a finding.",
                     "Headline groups use cases created after each model's documented training cutoff; where no cutoff is documented, every dated case "
                     "counts as possibly seen."],
                    "cluster-bootstrap (clusters by fix commit or release range)")


# --- CP5b: lifting ---------------------------------------------------------------------------------------------
def _cp5b(rd: _Reader) -> dict[str, Any]:
    d1, d4 = rd.json(RESULTS / "cp5b/lift_d1.json"), rd.json(RESULTS / "cp5b/lift_d4_ceiling.json")
    p1, p4 = "docs/results/cp5b/lift_d1.json", "docs/results/cp5b/lift_d4_ceiling.json"
    L = d1["lifting"]
    rows = [_count("cp5b.coverage", "Lifting: D1 cases (with curated derived symbols) where a core symbol lifted",
                   L["coverage"]["lifted_ok"], L["coverage"]["of"], [p1])]
    for rule in ("NEAREST", "ALL"):
        on = L["rules"][rule]["new_only"]["on_lifted"]
        rows += [_mean(f"cp5b.{rule.lower()}.precision", f"Lifting rule {rule}: precision of new symbols vs curated derived symbols", on["precision"], [p1]),
                 _mean(f"cp5b.{rule.lower()}.recall", f"Lifting rule {rule}: recall of new symbols vs curated derived symbols", on["recall"], [p1])]
    for alias, b in d1["e1_plus_l"].items():
        g = b["summary"]["headline"]
        for variant in ("add/NEAREST", "add/ALL"):
            rows.append(_delta(f"cp5b.e1l.{alias}.{variant.replace('/', '_')}.d_f1_e1",
                               f"E1+L F1 difference vs E1, variant {variant}, `{alias}` (gold: core + derived)",
                               g["core_derived"]["paired_vs_e1"][variant]["f1"], [p1]))
            rows.append(_delta(f"cp5b.e1l.{alias}.{variant.replace('/', '_')}.d_f1_e0",
                               f"E1+L F1 difference vs E0, variant {variant}, `{alias}` (gold: core + derived)",
                               g["core_derived"]["paired_vs_e0"][variant]["f1"], [p1]))
    s4 = d4["summary"]
    rows += [_count("cp5b.ceiling.within1", "D4 ceiling cases with a candidate within 1 call-graph hop of the missing function",
                    s4["within_1"]["count"], s4["within_1"]["of"], [p4]),
             _count("cp5b.ceiling.within2", "D4 ceiling cases with a candidate within 2 hops", s4["within_2"]["count"], s4["within_2"]["of"], [p4])]
    go = d1["environment"]["go"].split()[2]
    return _section("cp5b", "CP5b: lifting and caller/callee queries",
                    "Can walking up the call graph from a changed internal function to its exported callers recover the functions the advisory names, "
                    "and can graph expansion rescue the Mode 2 ceiling?", rows,
                    [f"Lifting ran with {go} fetched into a scratch directory because many modules need a newer Go than CI; the lifting evaluation is not "
                     "reproducible inside CI.",
                     "Neither lifting rule is good enough to sit inside the verdict path; it is a candidate-widening aid only.",
                     "E1+L beats E1 by adding symbols, but nothing beats the E0 baseline; it does not rescue the LLM pick.",
                     "The D4 ceiling investigation has a tiny n; the graph tools are an ablation, not a promised gain."],
                    "cluster-bootstrap (D1 clusters); counts for the ceiling")


# --- CP6: agent ------------------------------------------------------------------------------------------------
def _cp6(rd: _Reader) -> dict[str, Any]:
    d = RESULTS / "cp6"
    data = ar.load_cp6(rd.path(d), rd.root / RESULTS / "cp5")
    for p in sorted((rd.root / d).glob("*.json")):
        rd.read.add(str(p.relative_to(rd.root)))
    for alias in data["a1"]:
        rd.read.add(f"docs/results/cp5/select_release__{alias}__k10.json")
    agent, a1 = data["agent"], data["a1"]
    rows: list[dict[str, Any]] = []
    for alias in sorted({a for _arm, a in agent}):
        model_docs = {arm: doc for (arm, a), doc in agent.items() if a == alias}
        cases, lists, _notes = ar.arm_lists(model_docs, a1.get(alias))
        cutoff = next(iter(model_docs.values()))["model"]["cutoff"]
        mask = lr.group_defs(cases, cutoff)[0][2]
        sub = [c for c, m in zip(cases, mask) if m]
        g = st.Group([c["cluster_key"] for c in sub])
        src = [f"docs/results/cp6/agent__{arm}__{alias}.json" for arm in ("A2", "A3")] + [f"docs/results/cp5/select_release__{alias}__k10.json"]
        for arm in ("A0", "A1", "A2", "A3"):
            if arm in lists:
                s = dict(zip(ar.COLS, g.summary(ar._matrix(ar._sub(lists[arm], mask), sub))))
                rows.append(_mean(f"cp6.{alias}.{arm}.hit1", f"Agent experiment any-hit@1, arm {arm}, `{alias}` (headline group)", s["hit1"], src))
        for a, b in (("A2", "A0"), ("A3", "A0"), ("A3", "A1")):
            dd = ar.paired(cases, lists, mask, a, b)
            if dd is not None:
                rows.append(_delta(f"cp6.{alias}.d_{a}_{b}", f"Paired any-hit@1 difference, {a} minus {b}, `{alias}`", dd, src))
        if "A1" in lists:
            rows.append(_value(f"cp6.{alias}.A1_answered", f"Share of all cases the one-shot LLM (A1) answered, `{alias}`",
                               float(np.mean([bool(x) for x in lists["A1"]])), src, "{:.3f}"))
        # cost: mean prompt tokens and model+tool seconds per case, over runs that were run
        cost = {}
        for arm in ("A2", "A3"):
            doc = agent.get((arm, alias))
            if doc:
                run = [r for r in doc["rows"] if r["stop_reason"] != "NOT_RUN"]
                cost[arm] = (float(np.mean([r["input_tokens"] for r in run])), float(np.mean([r["agent_seconds"] for r in run])))
        if alias in a1:
            asked = [r for r in a1[alias]["rows"] if r["llm"]["status"] != "NOT_ASKED"]
            a1t, a1s = float(np.mean([r["llm"]["input_tokens"] for r in asked])), float(np.mean([r["llm"]["latency_s"] for r in asked]))
            for arm, (t, sec) in cost.items():
                rows.append(_value(f"cp6.{alias}.{arm}.token_ratio", f"Prompt tokens per case, {arm} divided by the one-shot LLM (A1), `{alias}`", t / a1t, src, "{:.1f}x"))
                rows.append(_value(f"cp6.{alias}.{arm}.seconds_ratio", f"Model+tool seconds per case, {arm} divided by A1, `{alias}`", sec / a1s, src, "{:.1f}x"))
        for arm in ("A2",):
            doc = agent.get((arm, alias))
            if doc:
                ran = [r for r in doc["rows"] if r["stop_reason"] != "NOT_RUN"]
                loops = [r for r in ran if r["stop_reason"] == "LOOP_DETECTED"]
                right = [r for r in loops if set(r["a0_top3"][:1]) & set(r["gold_ids"])]
                rows.append(_count(f"cp6.{alias}.{arm}.loops", f"Runs ended by the loop rule with no answer, {arm}, `{alias}` (of the runs that ran)",
                                   len(loops), len(ran), src[:1]))
                rows.append(_count(f"cp6.{alias}.{arm}.loops_a0_right", f"...of those, runs where retrieval's top-1 was right, {arm}, `{alias}`",
                                   len(right), len(loops), src[:1]))
    return _section("cp6", "CP6: the LangGraph investigation agent (Mode 2)",
                    "Does an agent that can read diffs and walk callers/callees pick the vulnerable function better than the retriever's top-1 (A0), "
                    "and at what cost?", rows,
                    ["The agent does not beat plain retrieval (A0). Any win is over the one-shot LLM baseline, which mostly did not answer for one model.",
                     "Cost is about five times the prompt tokens and about twice the seconds of the one-shot LLM.",
                     "The frozen loop rule ended many runs without an answer for one model; whether a looser rule helps was not tested and must not be "
                     "tuned on D4.",
                     "Headline wording was fixed before results; the failure analysis is a purposive sample, so its cause counts are not rates."],
                    "cluster-bootstrap (D4 ranges)")


